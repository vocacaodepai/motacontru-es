  await OB.gerarFasesModelo(ADM, id);
  const f = (await OB.detalhe(ADM, id)).fases;
  await OB.salvarFase(ADM, id, f[0].id, { progresso: 100 });
  await OB.salvarFase(ADM, id, f[1].id, { progresso: 50 });
