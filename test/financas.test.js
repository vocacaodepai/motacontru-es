test('cotação: compara fornecedores, escolhe a melhor e vira pedido de material', async () => {
  const id = await nova({ nome: 'Obra Cotação' });
  const [f1, f2, f3] = (await query('SELECT id FROM fornecedores ORDER BY id LIMIT 3')).map((x) => x.id);
  await assert.rejects(CP.criarCotacao(ENG, id, { descricao: 'Cimento', quantidade: 100, itens: [{ fornecedor_id: f1, valor_unit: 3500 }] }), /pelo menos 2/);
  await assert.rejects(CP.criarCotacao(ENG, id, { descricao: 'Cimento', quantidade: 100, itens: [{ fornecedor_id: f1, valor_unit: 3500 }, { fornecedor_id: f1, valor_unit: 3400 }] }), /repetido/);
  await assert.rejects(CP.criarCotacao(ENG, id, { descricao: '', quantidade: 100, itens: [] }), /Descreva/);
  const cot = await CP.criarCotacao(ENG, id, { descricao: 'Cimento CP-II', unidade: 'sc', quantidade: 100, itens: [{ fornecedor_id: f1, valor_unit: 3600, prazo_dias: 2 }, { fornecedor_id: f2, valor_unit: 3400, prazo_dias: 5 }] });
  await CP.registrarPreco(ENG, cot, { fornecedor_id: f3, valor_unit: 3900, prazo_dias: 1 });
  let [c] = await CP.listarCotacoes(ENG, { obra_id: id });
  assert.equal(c.itens.length, 3);
  assert.equal(c.itens[0].fornecedor_id, f2, 'o mais barato vem primeiro');
  assert.equal(c.melhor_item_id, c.itens[0].id);
  assert.equal(c.economia, (3900 - 3400) * 100);
  const r = await CP.escolher(ENG, cot, c.itens[0].id);
  assert.equal(r.status, 'pedido');
  const m = await one('SELECT * FROM obra_materiais WHERE id = $1', [r.material_id]);
  assert.equal(m.valor_unit, 3400);
  assert.equal(m.fornecedor_id, f2);
  assert.equal(m.entrega_prevista, d(5));
  [c] = await CP.listarCotacoes(ENG, { obra_id: id });
  assert.equal(c.status, 'fechada');
  await assert.rejects(CP.escolher(ENG, cot, c.itens[0].id), /encerrada/);
  await assert.rejects(CP.registrarPreco(ENG, cot, { fornecedor_id: f1, valor_unit: 1 }), /encerrada/);
  const cot2 = await CP.criarCotacao(ADM, id, { descricao: 'Areia', quantidade: 10, itens: [{ fornecedor_id: f1, valor_unit: 100 }, { fornecedor_id: f2, valor_unit: 90 }] });
  await CP.cancelarCotacao(ADM, cot2);
  assert.equal((await CP.listarCotacoes(ADM, { status: 'cancelada' })).length, 1);
  await CP.definirLimite(ADM, 100000);
  const cot3 = await CP.criarCotacao(ENG, id, { descricao: 'Areia grande', quantidade: 1000, itens: [{ fornecedor_id: f1, valor_unit: 500 }, { fornecedor_id: f2, valor_unit: 450 }] });
  const r3 = await CP.escolher(ENG, cot3, (await CP.listarCotacoes(ENG, { status: 'aberta' }))[0].itens[0].id);
  assert.equal(r3.status, 'aguardando_aprovacao', 'cotação grande também passa pela aprovação');
  await CP.definirLimite(ADM, 0);
});

test('folha de diárias: presença × diária, paga uma única vez e lança no caixa por obra', async () => {
  const id = await nova({ nome: 'Obra Folha' });
  const mk = async (nome, diaria) => (await one('INSERT INTO funcionarios (nome, funcao_obra, valor_diaria, regime) VALUES ($1, $2, $3, $4) RETURNING id', [nome, 'peao', diaria, diaria ? 'diarista' : 'clt'])).id;
  const [a, b, clt] = [await mk('Diarista A', 20000), await mk('Diarista B', 25000), await mk('Salariado', null)];
  for (const f of [a, b, clt]) await OB.alocar(ADM, id, { funcionario_id: f });
  const seg = FO.segundaDe(hoje), dia = (n) => S.addDias(seg, n);
  assert.equal(FO.segundaDe(dia(3)), seg);
  const semanaPassada = S.addDias(seg, -7);
  const marcar = (data, regs) => OB.registrarPresenca(ENG, id, { data, registros: regs });
  await marcar(S.addDias(semanaPassada, 0), [{ funcionario_id: a, situacao: 'presente' }, { funcionario_id: b, situacao: 'presente' }, { funcionario_id: clt, situacao: 'presente' }]);
  await marcar(S.addDias(semanaPassada, 1), [{ funcionario_id: a, situacao: 'presente' }, { funcionario_id: b, situacao: 'falta' }, { funcionario_id: clt, situacao: 'presente' }]);
  await marcar(S.addDias(semanaPassada, 2), [{ funcionario_id: a, situacao: 'atraso' }, { funcionario_id: b, situacao: 'presente' }]);
  const s = await FO.semana(S.addDias(semanaPassada, 4));
  assert.equal(s.inicio, semanaPassada);
  const la = s.linhas.find((l) => l.funcionario_id === a), lb = s.linhas.find((l) => l.funcionario_id === b);
  assert.equal(la.dias, 3);
  assert.equal(la.valor, 60000);
  assert.equal(lb.dias, 2);
  assert.equal(lb.faltas, 1);
  assert.equal(lb.valor, 50000);
  assert.ok(!s.linhas.some((l) => l.funcionario_id === clt), 'quem não tem diária não entra na folha');
  assert.equal(s.pendente, 110000);
  await assert.rejects(FO.pagar(ADM, { semana: semanaPassada }), /conta/);
  const r = await FO.pagar(FIN, { semana: semanaPassada, conta_id: conta });
  assert.equal(r.pagos, 2);
  assert.equal(r.total, 110000);
  const l = (await S.listarLancamentos({ obra_id: id })).filter((x) => x.categoria === 'Diárias');
  assert.equal(l.length, 2);
  assert.ok(l.every((x) => x.obra_id === id && x.tipo === 'saida' && /Diárias/.test(x.descricao)));
  const depois = await FO.semana(semanaPassada);
  assert.equal(depois.pendente, 0);
  assert.equal(depois.pago, 110000);
  await assert.rejects(FO.pagar(FIN, { semana: semanaPassada, conta_id: conta }), /Nada pendente/);
  assert.equal((await OB.detalhe(ADM, id)).obra.custo_pago, 110000);
  await assert.rejects(FO.pagar(FIN, { semana: S.addDias(seg, 14), conta_id: conta }), /Nada pendente|ainda não começou/);
});

