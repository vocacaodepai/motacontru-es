  assert.ok(plan.every((v, i) => i === 0 || v >= plan[i - 1]), 'planejado nunca diminui');
  assert.equal(plan.at(-1), 100);
  assert.ok(c.serie.filter((p) => p.data > hoje).every((p) => p.realizado === null && p.custo === null), 'nada de realizado no futuro');
